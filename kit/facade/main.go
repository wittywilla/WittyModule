// Command facade writes both ends of a service module's calls, so a server can use a module's
// packages by name with none of its code compiled in. From each listed package it copies the
// exported types and constants as they are, and writes:
//
//   - for the server, a stub for each exported function and method, which makes the call over
//     the module's service connection (wittymodule/service);
//   - for the module, the code that answers each one.
//
// Run it again after a package changes:
//
//	go run github.com/wittywilla/wittymodule/kit/facade -config facade.json -module <folder> -server <folder>
//
// A signature it can't carry (a func, a channel, an interface) is left out and listed, and is
// written by hand beside what it generates, in the server's folder and in the module's.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// Config says what to do.
type Config struct {
	Module   string    `json:"module"` // the module's id
	Rpc      string    `json:"rpc"`    // the module's folder for what answers calls, such as "rpc"
	Packages []Package `json:"packages"`
}

// Package is one package of the module.
type Package struct {
	Import string `json:"import"` // its import path in the module
	Dir    string `json:"dir"`    // its folder in the module
	Name   string `json:"name"`   // its package name
	Out    string `json:"out"`    // the server's folder for its stubs
	OutImp string `json:"outImport"`
	// Manual names types, functions and methods ("Type.Method") written by hand, on both sides.
	Manual []string `json:"manual,omitempty"`
	// Local names functions and methods copied as they are, not called: small, pure, and asked
	// for constantly.
	Local []string `json:"local,omitempty"`
	// Resolve maps a type whose values live in the module to the function in the rpc package
	// that finds one from what the server sends.
	Resolve map[string]string `json:"resolve,omitempty"`
}

type decl struct {
	node ast.Decl
	file *ast.File
	src  []byte
	path string
}

type pkgInfo struct {
	cfg     Package
	fset    *token.FileSet
	decls   []*decl
	types   map[string]*decl
	values  map[string]*decl
	funcs   map[string]*decl // Name or Type.Method
	manual  map[string]bool
	local   map[string]bool
	skipped []string
	errs    []string // exported error variables
}

func main() {
	cfgPath := flag.String("config", "facade.json", "")
	modDir := flag.String("module", ".", "the module's folder")
	srvDir := flag.String("server", "", "the server's folder")
	flag.Parse()
	var cfg Config
	b, err := os.ReadFile(*cfgPath)
	if err != nil {
		fatal(err)
	}
	if err := json.Unmarshal(b, &cfg); err != nil {
		fatal(err)
	}
	var pkgs []*pkgInfo
	for _, p := range cfg.Packages {
		pi, err := load(*modDir, p)
		if err != nil {
			fatal(err)
		}
		pkgs = append(pkgs, pi)
	}
	byName := map[string]*pkgInfo{}
	for _, p := range pkgs {
		byName[p.cfg.Name] = p
	}
	var dispatch bytes.Buffer
	fmt.Fprintf(&dispatch, "// Code generated by kit/facade in WittyModule. Run it again rather than editing this.\n\npackage %s\n\n", filepath.Base(cfg.Rpc))
	imports := map[string]string{}
	var cases, sentinels bytes.Buffer
	for _, p := range pkgs {
		out, err := stubs(cfg, p, byName, &cases, &sentinels, imports)
		if err != nil {
			fatal(err)
		}
		if *srvDir != "" {
			dst := filepath.Join(*srvDir, filepath.FromSlash(p.cfg.Out), "gen.go")
			if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
				fatal(err)
			}
			if err := os.WriteFile(dst, out, 0o644); err != nil {
				fatal(err)
			}
			fmt.Println("wrote", dst)
		}
		for _, s := range p.skipped {
			fmt.Printf("  by hand: %s.%s\n", p.cfg.Name, s)
		}
	}
	dispatch.WriteString("import (\n\t\"context\"\n\t\"encoding/json\"\n\t\"errors\"\n")
	var imps []string
	for i := range imports {
		imps = append(imps, i)
	}
	sort.Strings(imps)
	for _, i := range imps {
		fmt.Fprintf(&dispatch, "\t%s %q\n", imports[i], i)
	}
	dispatch.WriteString("\n\t\"github.com/wittywilla/wittymodule/service\"\n)\n\n")
	dispatch.WriteString("var _ = context.Background\nvar _ = errors.Is\nvar _ json.RawMessage\n\n")
	dispatch.WriteString("// Handlers answer the server's calls, by name.\nvar Handlers = map[string]service.Handler{\n")
	dispatch.Write(cases.Bytes())
	dispatch.WriteString("}\n\n// ErrorCode names an error the server has its own copy of.\nfunc ErrorCode(err error) string {\n\tswitch {\n")
	dispatch.Write(sentinels.Bytes())
	dispatch.WriteString("\t}\n\treturn \"\"\n}\n")
	src, err := format.Source(dispatch.Bytes())
	if err != nil {
		_ = os.WriteFile(filepath.Join(*modDir, cfg.Rpc, "gen.go"), dispatch.Bytes(), 0o644)
		fatal(fmt.Errorf("the module's side: %w", err))
	}
	if err := os.MkdirAll(filepath.Join(*modDir, cfg.Rpc), 0o755); err != nil {
		fatal(err)
	}
	if err := os.WriteFile(filepath.Join(*modDir, cfg.Rpc, "gen.go"), src, 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("wrote", filepath.Join(*modDir, cfg.Rpc, "gen.go"))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "facade:", err)
	os.Exit(1)
}

func load(modDir string, p Package) (*pkgInfo, error) {
	pi := &pkgInfo{cfg: p, fset: token.NewFileSet(), types: map[string]*decl{}, values: map[string]*decl{}, funcs: map[string]*decl{}, manual: map[string]bool{}, local: map[string]bool{}}
	for _, m := range p.Manual {
		pi.manual[m] = true
	}
	for _, m := range p.Local {
		pi.local[m] = true
	}
	files, err := filepath.Glob(filepath.Join(modDir, filepath.FromSlash(p.Dir), "*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	for _, path := range files {
		base := filepath.Base(path)
		if strings.HasSuffix(base, "_test.go") || hasOS(base) {
			continue
		}
		src, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		f, err := parser.ParseFile(pi.fset, path, src, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			dd := &decl{node: d, file: f, src: src, path: path}
			pi.decls = append(pi.decls, dd)
			switch x := d.(type) {
			case *ast.FuncDecl:
				name := x.Name.Name
				if x.Recv != nil {
					name = recvName(x) + "." + name
				}
				pi.funcs[name] = dd
			case *ast.GenDecl:
				for _, s := range x.Specs {
					switch y := s.(type) {
					case *ast.TypeSpec:
						pi.types[y.Name.Name] = dd
					case *ast.ValueSpec:
						for _, n := range y.Names {
							pi.values[n.Name] = dd
						}
					}
				}
			}
		}
	}
	return pi, nil
}

func hasOS(base string) bool {
	n := strings.TrimSuffix(base, ".go")
	for _, s := range []string{"_linux", "_windows", "_darwin", "_freebsd", "_other", "_unix", "_amd64", "_arm64"} {
		if strings.HasSuffix(n, s) {
			return true
		}
	}
	return false
}

func recvName(f *ast.FuncDecl) string {
	t := f.Recv.List[0].Type
	if s, ok := t.(*ast.StarExpr); ok {
		t = s.X
	}
	if ix, ok := t.(*ast.IndexExpr); ok {
		t = ix.X
	}
	if i, ok := t.(*ast.Ident); ok {
		return i.Name
	}
	return ""
}

func exported(n string) bool { return ast.IsExported(n) }

// typeText prints a type expression.
func (p *pkgInfo) text(n ast.Node) string {
	var b bytes.Buffer
	if err := printer.Fprint(&b, p.fset, n); err != nil {
		return ""
	}
	return b.String()
}

// carries says whether a type can travel: no funcs, channels or interfaces in the expression
// itself, and nothing from a package that can't be sent.
func (p *pkgInfo) carries(e ast.Expr) bool {
	ok := true
	ast.Inspect(e, func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.FuncType, *ast.ChanType:
			ok = false
		case *ast.InterfaceType:
			_ = x
			ok = false
		case *ast.SelectorExpr:
			if id, isID := x.X.(*ast.Ident); isID {
				switch id.Name + "." + x.Sel.Name {
				case "time.Time", "time.Duration", "json.RawMessage", "net.IP", "net.HardwareAddr":
				case "context.Context":
				default:
					// Another package of this module is fine; anything else is for a person.
					if id.Name == "http" || id.Name == "io" || id.Name == "os" || id.Name == "net" || id.Name == "slog" || id.Name == "exec" || id.Name == "sync" {
						ok = false
					}
				}
			}
		}
		return ok
	})
	return ok
}

func isContext(p *pkgInfo, e ast.Expr) bool { return p.text(e) == "context.Context" }
func isError(p *pkgInfo, e ast.Expr) bool   { return p.text(e) == "error" }

type param struct {
	name     string
	typ      string
	variadic bool
	ctx      bool
}

func (p *pkgInfo) params(fl *ast.FieldList) ([]param, bool) {
	var out []param
	if fl == nil {
		return nil, true
	}
	i := 0
	for _, f := range fl.List {
		t := f.Type
		variadic := false
		if e, ok := t.(*ast.Ellipsis); ok {
			variadic = true
			t = e.Elt
		}
		if !p.carries(t) {
			return nil, false
		}
		names := f.Names
		if len(names) == 0 {
			names = []*ast.Ident{ast.NewIdent(fmt.Sprintf("a%d", i))}
		}
		for _, n := range names {
			name := n.Name
			if name == "_" {
				name = fmt.Sprintf("a%d", i)
			}
			out = append(out, param{name: name, typ: p.text(t), variadic: variadic, ctx: isContext(p, t)})
			i++
		}
	}
	return out, true
}

func (p *pkgInfo) results(fl *ast.FieldList) (types []string, hasErr, ok bool) {
	if fl == nil {
		return nil, false, true
	}
	var all []ast.Expr
	for _, f := range fl.List {
		n := max(len(f.Names), 1)
		for range n {
			all = append(all, f.Type)
		}
	}
	for i, t := range all {
		if i == len(all)-1 && isError(p, t) {
			return types, true, true
		}
		if !p.carries(t) {
			return nil, false, false
		}
		types = append(types, p.text(t))
	}
	return types, false, true
}

// qualify writes a type as the module's side sees it: names of this package get its name.
func qualify(typ, pkg string, types map[string]*decl) string {
	var b strings.Builder
	i := 0
	for i < len(typ) {
		c := typ[i]
		if c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' {
			j := i
			for j < len(typ) && (typ[j] == '_' || typ[j] == '.' || typ[j] >= 'a' && typ[j] <= 'z' || typ[j] >= 'A' && typ[j] <= 'Z' || typ[j] >= '0' && typ[j] <= '9') {
				j++
			}
			w := typ[i:j]
			if types[w] != nil && !strings.Contains(w, ".") {
				b.WriteString(pkg + "." + w)
			} else {
				b.WriteString(w)
			}
			i = j
			continue
		}
		b.WriteByte(c)
		i++
	}
	return b.String()
}

// stubs writes the server's file for a package, and adds the module's cases for it.
func stubs(cfg Config, p *pkgInfo, all map[string]*pkgInfo, cases, sentinels *bytes.Buffer, imports map[string]string) ([]byte, error) {
	var body bytes.Buffer
	want := map[*decl]bool{}
	imports[p.cfg.Import] = p.cfg.Name

	// What's copied: every exported type and constant, and whatever they refer to here.
	var visit func(d *decl)
	visit = func(d *decl) {
		if want[d] {
			return
		}
		want[d] = true
		ast.Inspect(d.node, func(n ast.Node) bool {
			// A function's body isn't copied unless it's local, so it refers to nothing.
			if fd, ok := n.(*ast.FuncDecl); ok && !isLocal(p, fd) {
				if fd.Recv != nil {
					ast.Inspect(fd.Recv, func(m ast.Node) bool { return follow(p, m, visit) })
				}
				ast.Inspect(fd.Type, func(m ast.Node) bool { return follow(p, m, visit) })
				return false
			}
			return follow(p, n, visit)
		})
	}
	for _, d := range p.decls {
		gd, ok := d.node.(*ast.GenDecl)
		if !ok || gd.Tok == token.IMPORT {
			continue
		}
		for _, s := range gd.Specs {
			switch y := s.(type) {
			case *ast.TypeSpec:
				if exported(y.Name.Name) && !p.manual[y.Name.Name] {
					visit(d)
				}
			case *ast.ValueSpec:
				if gd.Tok == token.CONST {
					for _, n := range y.Names {
						if exported(n.Name) && !p.manual[n.Name] {
							visit(d)
						}
					}
				}
			}
		}
	}
	// Functions that are copied as they are.
	for name := range p.local {
		if d := p.funcs[name]; d != nil {
			visit(d)
		} else if d := p.values[name]; d != nil {
			visit(d)
		}
	}
	// Exported errors, which the server keeps a copy of so errors.Is still works.
	var errNames []string
	for name, d := range p.values {
		if !exported(name) || p.manual[name] || !strings.HasPrefix(name, "Err") {
			continue
		}
		gd := d.node.(*ast.GenDecl)
		if gd.Tok == token.VAR {
			errNames = append(errNames, name)
		}
	}
	sort.Strings(errNames)

	used := map[string]string{}
	// The copied declarations, in the order they're written in the module.
	for _, d := range p.decls {
		if !want[d] {
			continue
		}
		if fd, ok := d.node.(*ast.FuncDecl); ok && !isLocal(p, fd) {
			continue
		}
		gd, isGen := d.node.(*ast.GenDecl)
		if isGen && gd.Tok == token.VAR && !wantedVar(p, gd) {
			continue
		}
		text := p.declText(d)
		body.WriteString(text + "\n\n")
		noteImports(d, used)
	}
	// Errors.
	if len(errNames) > 0 {
		body.WriteString("// What the module's errors are, so errors.Is works on what comes back.\nvar (\n")
		for _, e := range errNames {
			msg := errText(p.values[e], e)
			fmt.Fprintf(&body, "\t%s = errors.New(%s)\n", e, msg)
			fmt.Fprintf(sentinels, "\tcase errors.Is(err, %s.%s):\n\t\treturn %q\n", p.cfg.Name, e, p.cfg.Name+"."+e)
		}
		body.WriteString(")\n\nfunc init() {\n")
		for _, e := range errNames {
			fmt.Fprintf(&body, "\tservice.RegisterError(%q, %s)\n", p.cfg.Name+"."+e, e)
		}
		body.WriteString("}\n\n")
		used["errors"] = "errors"
	}

	// The functions and methods.
	var names []string
	for n := range p.funcs {
		names = append(names, n)
	}
	sort.Strings(names)
	stubbed := 0
	for _, name := range names {
		d := p.funcs[name]
		fd := d.node.(*ast.FuncDecl)
		if !exported(fd.Name.Name) || p.manual[name] || p.local[name] {
			continue
		}
		recv := ""
		if fd.Recv != nil {
			recv = recvName(fd)
			if !exported(recv) || p.manual[recv] && p.cfg.Resolve[recv] == "" {
				continue
			}
		}
		ps, ok1 := p.params(fd.Type.Params)
		rs, hasErr, ok2 := p.results(fd.Type.Results)
		if !ok1 || !ok2 || fd.Type.TypeParams != nil {
			p.skipped = append(p.skipped, name)
			continue
		}
		noteImports(d, used)
		writeStub(&body, p, cfg, fd, name, recv, ps, rs, hasErr, used)
		writeCase(cases, p, fd, name, recv, ps, rs, hasErr, all, imports)
		stubbed++
	}
	if stubbed > 0 {
		used["github.com/wittywilla/wittymodule/service"] = "service"
		used["context"] = "context"
	}

	// Imports: only what the text uses.
	text := body.String()
	var head bytes.Buffer
	head.WriteString("// Code generated by kit/facade in WittyModule. Run it again rather than editing this.\n\n")
	fmt.Fprintf(&head, "// Package %s is what a server knows of the module's package of that name: its types and\n// constants as they are, and a call to the module for everything it does.\npackage %s\n\nimport (\n", p.cfg.Name, p.cfg.Name)
	var ps []string
	for i := range used {
		ps = append(ps, i)
	}
	sort.Strings(ps)
	for _, i := range ps {
		n := used[i]
		if !usesPackage(text, n) {
			continue
		}
		// A sibling package of the module comes from the server's own copy.
		imp := i
		for _, o := range all {
			if i == o.cfg.Import {
				imp = o.cfg.OutImp
			}
		}
		fmt.Fprintf(&head, "\t%s %q\n", n, imp)
	}
	head.WriteString(")\n\n")
	head.WriteString(text)
	src, err := format.Source(head.Bytes())
	if err != nil {
		bad := filepath.Join(os.TempDir(), "facade-"+p.cfg.Name+".go")
		_ = os.WriteFile(bad, head.Bytes(), 0o644)
		return nil, fmt.Errorf("%s (see %s): %w", p.cfg.Name, bad, err)
	}
	return src, nil
}

// usesPackage says whether a package's name is used in code: as itself, not as the end of
// another name or a field.
func usesPackage(text, name string) bool {
	re := regexp.MustCompile(`(^|[^.\w"/])` + regexp.QuoteMeta(name) + `\.[A-Z]`)
	return re.MatchString(text)
}

func isLocal(p *pkgInfo, fd *ast.FuncDecl) bool {
	name := fd.Name.Name
	if fd.Recv != nil {
		name = recvName(fd) + "." + name
	}
	return p.local[name] || !exported(fd.Name.Name) && p.localHelper(name)
}

// localHelper: an unexported function pulled in by a local one.
func (p *pkgInfo) localHelper(string) bool { return true }

func follow(p *pkgInfo, n ast.Node, visit func(*decl)) bool {
	if id, ok := n.(*ast.Ident); ok {
		if d := p.types[id.Name]; d != nil && !p.manual[id.Name] {
			visit(d)
		} else if d := p.values[id.Name]; d != nil && !p.manual[id.Name] {
			visit(d)
		} else if d := p.funcs[id.Name]; d != nil && !p.manual[id.Name] {
			if fd := d.node.(*ast.FuncDecl); fd.Recv == nil && (!exported(fd.Name.Name) || p.local[id.Name]) {
				visit(d)
			}
		}
	}
	return true
}

// wantedVar keeps variables a local function needs: errors have a line of their own.
func wantedVar(p *pkgInfo, gd *ast.GenDecl) bool {
	for _, s := range gd.Specs {
		if v, ok := s.(*ast.ValueSpec); ok {
			for _, n := range v.Names {
				if strings.HasPrefix(n.Name, "Err") && exported(n.Name) {
					return false
				}
			}
		}
	}
	return true
}

func errText(d *decl, name string) string {
	gd := d.node.(*ast.GenDecl)
	for _, s := range gd.Specs {
		if v, ok := s.(*ast.ValueSpec); ok {
			for i, n := range v.Names {
				if n.Name == name && i < len(v.Values) {
					if c, ok := v.Values[i].(*ast.CallExpr); ok && len(c.Args) > 0 {
						if l, ok := c.Args[0].(*ast.BasicLit); ok {
							return l.Value
						}
					}
				}
			}
		}
	}
	return fmt.Sprintf("%q", name)
}

// declText prints a declaration with struct fields that can't travel taken out or marked.
func (p *pkgInfo) declText(d *decl) string {
	if gd, ok := d.node.(*ast.GenDecl); ok && gd.Tok == token.TYPE {
		for _, s := range gd.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok {
				if st, ok := ts.Type.(*ast.StructType); ok && st.Fields != nil {
					var keep []*ast.Field
					for _, f := range st.Fields.List {
						// Unexported fields can't travel, and nothing here can reach them.
						names := f.Names[:0:0]
						for _, n := range f.Names {
							if exported(n.Name) {
								names = append(names, n)
							}
						}
						if len(f.Names) > 0 && len(names) == 0 {
							continue
						}
						f.Names = names
						if !p.carries(f.Type) {
							f.Tag = &ast.BasicLit{Kind: token.STRING, Value: "`json:\"-\"`"}
						}
						keep = append(keep, f)
					}
					st.Fields.List = keep
				}
			}
		}
		var b bytes.Buffer
		_ = printer.Fprint(&b, p.fset, gd)
		doc := ""
		if gd.Doc != nil {
			doc = gd.Doc.Text()
		}
		_ = doc
		return b.String()
	}
	var start token.Pos
	switch x := d.node.(type) {
	case *ast.FuncDecl:
		start = x.Pos()
		if x.Doc != nil {
			start = x.Doc.Pos()
		}
	case *ast.GenDecl:
		start = x.Pos()
		if x.Doc != nil {
			start = x.Doc.Pos()
		}
	}
	return string(d.src[p.fset.Position(start).Offset:p.fset.Position(d.node.End()).Offset])
}

func noteImports(d *decl, used map[string]string) {
	for _, im := range d.file.Imports {
		path := strings.Trim(im.Path.Value, `"`)
		name := path[strings.LastIndex(path, "/")+1:]
		if im.Name != nil {
			name = im.Name.Name
		}
		used[path] = name
	}
}

func writeStub(b *bytes.Buffer, p *pkgInfo, cfg Config, fd *ast.FuncDecl, name, recv string, ps []param, rs []string, hasErr bool, used map[string]string) {
	if fd.Doc != nil {
		b.WriteString(fd.Doc.Text()[:0])
		for _, c := range fd.Doc.List {
			b.WriteString(c.Text + "\n")
		}
	}
	b.WriteString("func ")
	recvName := ""
	ptr := false
	if fd.Recv != nil {
		f := fd.Recv.List[0]
		recvName = "recv"
		if len(f.Names) > 0 && f.Names[0].Name != "_" {
			recvName = f.Names[0].Name
		}
		_, ptr = f.Type.(*ast.StarExpr)
		fmt.Fprintf(b, "(%s %s) ", recvName, p.text(f.Type))
	}
	b.WriteString(fd.Name.Name + "(")
	ctxName := ""
	var args []string
	for i, a := range ps {
		if i > 0 {
			b.WriteString(", ")
		}
		pre := ""
		if a.variadic {
			pre = "..."
		}
		fmt.Fprintf(b, "%s %s%s", a.name, pre, a.typ)
		if a.ctx {
			ctxName = a.name
		} else {
			args = append(args, a.name)
		}
	}
	b.WriteString(") ")
	var rets []string
	rets = append(rets, rs...)
	if hasErr {
		rets = append(rets, "error")
	}
	switch len(rets) {
	case 0:
	case 1:
		b.WriteString(rets[0] + " ")
	default:
		b.WriteString("(" + strings.Join(rets, ", ") + ") ")
	}
	b.WriteString("{\n")
	if ctxName == "" {
		ctxName = "context.Background()"
	}
	var outs, retNames []string
	for i, t := range rs {
		fmt.Fprintf(b, "\tvar r%d %s\n", i, t)
		outs = append(outs, fmt.Sprintf("&r%d", i))
		retNames = append(retNames, fmt.Sprintf("r%d", i))
	}
	recvArg := "nil"
	if fd.Recv != nil {
		recvArg = recvName
	}
	backTo := "nil"
	if ptr {
		backTo = recvName
	}
	argList := "nil"
	if len(args) > 0 {
		argList = "[]any{" + strings.Join(args, ", ") + "}"
	}
	outList := "nil"
	if len(outs) > 0 {
		outList = "[]any{" + strings.Join(outs, ", ") + "}"
	}
	call := fmt.Sprintf("service.Call(%s, %q, %q, %s, %s, %s, %s)", ctxName, cfg.Module, p.cfg.Name+"."+name, recvArg, backTo, argList, outList)
	if hasErr {
		fmt.Fprintf(b, "\terr := %s\n", call)
		retNames = append(retNames, "err")
	} else {
		fmt.Fprintf(b, "\t_ = %s\n", call)
	}
	if len(retNames) > 0 {
		b.WriteString("\treturn " + strings.Join(retNames, ", ") + "\n")
	}
	b.WriteString("}\n\n")
}

func writeCase(c *bytes.Buffer, p *pkgInfo, fd *ast.FuncDecl, name, recv string, ps []param, rs []string, hasErr bool, all map[string]*pkgInfo, imports map[string]string) {
	pkg := p.cfg.Name
	fmt.Fprintf(c, "\t%q: func(ctx context.Context, rawRecv json.RawMessage, args []json.RawMessage) (rets []any, back any, err error) {\n", pkg+"."+name)
	n := 0
	var callArgs []string
	for _, a := range ps {
		if a.ctx {
			callArgs = append(callArgs, "ctx")
			continue
		}
		t := qualify(a.typ, pkg, p.types)
		fmt.Fprintf(c, "\t\tvar a%d %s\n", n, sliceIf(a.variadic, t))
		fmt.Fprintf(c, "\t\tif err := service.Arg(args, %d, &a%d); err != nil {\n\t\t\treturn nil, nil, err\n\t\t}\n", n, n)
		arg := fmt.Sprintf("a%d", n)
		if a.variadic {
			arg += "..."
		}
		callArgs = append(callArgs, arg)
		n++
	}
	target := pkg + "." + fd.Name.Name
	if fd.Recv != nil {
		_, ptr := fd.Recv.List[0].Type.(*ast.StarExpr)
		if res := p.cfg.Resolve[recv]; res != "" {
			fmt.Fprintf(c, "\t\trecv, err := %s(rawRecv)\n\t\tif err != nil {\n\t\t\treturn nil, nil, err\n\t\t}\n", res)
		} else {
			fmt.Fprintf(c, "\t\tvar recv %s.%s\n\t\tif err := service.Recv(rawRecv, &recv); err != nil {\n\t\t\treturn nil, nil, err\n\t\t}\n", pkg, recv)
			if ptr {
				c.WriteString("\t\tback = &recv\n")
			}
		}
		target = "recv." + fd.Name.Name
	}
	var outs []string
	for i := range rs {
		outs = append(outs, fmt.Sprintf("r%d", i))
	}
	lhs := append([]string(nil), outs...)
	if hasErr {
		lhs = append(lhs, "err")
	}
	callText := target + "(" + strings.Join(callArgs, ", ") + ")"
	if len(lhs) == 0 {
		fmt.Fprintf(c, "\t\t%s\n", callText)
	} else {
		op := ":="
		if len(lhs) == 1 && hasErr {
			op = "="
		}
		fmt.Fprintf(c, "\t\t%s %s %s\n", strings.Join(lhs, ", "), op, callText)
	}
	if len(outs) > 0 {
		fmt.Fprintf(c, "\t\treturn []any{%s}, back, err\n", strings.Join(outs, ", "))
	} else {
		c.WriteString("\t\treturn nil, back, err\n")
	}
	c.WriteString("\t},\n")
}

func sliceIf(on bool, t string) string {
	if on {
		return "[]" + t
	}
	return t
}
